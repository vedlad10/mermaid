/**
 * demo-journey.ts — the whole revenue cycle, end to end, on a laptop, in one command.
 *
 *   npm run demo:journey                  # runs five journeys, then keeps the app up to look at
 *   npm run demo:journey -- --exit        # runs them and exits 0 (all passed) or 1 (one did not)
 *   npm run demo:journey -- --port 3200   # default 3108; 0 picks a free port
 *
 * Boots the REAL application (`createApp(buildServices())`, the composition root `npm run web` uses)
 * IN MEMORY, then drives it over HTTP exactly as the browser does: verify a card → the claim the
 * outbox builds from it → the scrubber and the human submit gate → the payer's 835 → posting → the
 * denial queue → an appeal a person approves. Afterwards the same server stays up, so every claim,
 * advice and denial these journeys made can be opened in the UI.
 *
 * ── WHAT IS REAL AND WHAT IS NOT ───────────────────────────────────────────────────────────────
 * Real: every rule, parser, scrubber, posting, ledger and gate in the product. Mock: the
 * clearinghouse. The payer's 271 and 835 are generated by the mock adapter (production parsers
 * read them) from documented member-id levers — ends 00 → coverage terminated, 77 → pre-auth
 * denial (CARC 197), 99 → annual maximum reached, 23 → another plan is named (coordination of
 * benefits). No database, no login, nothing persists after Ctrl+C.
 *
 * ── THE SAFETY PIN ─────────────────────────────────────────────────────────────────────────────
 * `.env` selects the Stedi adapter. It is pinned to `mock` BEFORE any module reads config and the
 * memoized adapter is cleared, the same pin `scripts/mock-scenarios.ts` and the live-DB harness use;
 * the run refuses to start if the pin did not take. DATABASE_URL is removed for the same reason
 * `scripts/serve-demo.mjs` removes it: this must never quietly come up against a real database.
 */
process.env.EDI_ADAPTER = "mock";
delete process.env.DATABASE_URL;
delete process.env.DATABASE_ADMIN_URL;
const { resetEdiAdapter, getEdiAdapter } = await import("@mermaid/edi");
resetEdiAdapter();
import type { AddressInfo } from "node:net";
const { createApp, buildServices } = await import("../apps/web/server.ts");

if (getEdiAdapter().constructor.name !== "MockEdiAdapter") {
  console.error(`REFUSING: the EDI adapter is ${getEdiAdapter().constructor.name}, not the mock.`);
  process.exit(1);
}

const arg = (name: string): string | undefined => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
};
const exitAfter = process.argv.includes("--exit");
const port = Number(arg("port") ?? 3108);
if (!Number.isInteger(port) || port < 0 || port > 65535) {
  console.error(`--port ${arg("port")} is not a port.`);
  process.exit(2);
}

const services = buildServices({ inMemory: true });
if (services.persistent) {
  console.error("REFUSING: services came up persistent; this script only runs in memory.");
  process.exit(1);
}
await services.payerProfile.ensureDefaults();
const server = createApp(services);
await new Promise<void>((resolve) => server.listen(port, "127.0.0.1", () => resolve()));
const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;

// ── HTTP, as the browser does it ──────────────────────────────────────────────────────────────
async function call(method: string, path: string, body?: unknown): Promise<{ status: number; json: any }> {
  const r = await fetch(base + path, {
    method,
    headers: body === undefined ? undefined : { "content-type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  return { status: r.status, json: await r.json().catch(() => ({})) };
}

const usd = (c: unknown): string => (typeof c === "number" && Number.isFinite(c) ? `$${(c / 100).toFixed(2)}` : "?");
/** Obviously synthetic and undeliverable: the 837D needs a subscriber address, and no real one may appear. */
const SYNTHETIC_ADDRESS = { street: "1 SYNTHETIC TEST WAY", city: "SPRINGFIELD", state: "CA", zip: "900010000" } as const;
const PLAN = [
  { code: "D0120", quantity: 1 },
  { code: "D1110", quantity: 1, feeDollars: 110 },
  { code: "D2750", quantity: 1, feeDollars: 1250, toothNumber: "19" },
];
const ACTOR = "demo.biller@synthetic.invalid";

interface Outcome {
  id: string;
  title: string;
  passed: boolean;
  steps: string[];
  problem: string | null;
}
const outcomes: Outcome[] = [];

/**
 * One journey. `check` failures are the product not doing what the journey documents; a journey
 * stops at the first one and says where. Nothing is retried and nothing is asserted that the mock
 * lever does not determine.
 */
async function journey(
  id: string,
  title: string,
  patient: { firstName: string; lastName: string; dateOfBirth: string; memberId: string; payer: string },
  after: (ctx: { claimId: string | null; verificationStatus: string; step: (s: string) => void; check: (ok: boolean, why: string) => void }) => Promise<void>
): Promise<void> {
  const o: Outcome = { id, title, passed: true, steps: [], problem: null };
  outcomes.push(o);
  const step = (s: string) => o.steps.push(s);
  const check = (ok: boolean, why: string) => {
    if (!ok) throw new Error(why);
  };
  try {
    const v = await call("POST", "/api/v1/verifications", {
      patient: { ...patient, payer: undefined, address: SYNTHETIC_ADDRESS },
      cardText: `${patient.payer}\nMember ID: ${patient.memberId}\nGroup #: SYNGRP`,
      planItems: PLAN,
    });
    check(v.status === 201, `verification returned HTTP ${v.status}: ${JSON.stringify(v.json?.error ?? v.json).slice(0, 200)}`);
    const record = v.json.record;
    step(`eligibility checked with ${patient.payer} · record ${record.status} · decision ${v.json.decision?.outcome ?? "?"}`);
    const claims = (await call("GET", "/api/v1/claims")).json.items ?? [];
    const mine = claims.filter((c: any) => c.verificationId === record.id);
    await after({ claimId: mine.at(-1)?.id ?? null, verificationStatus: record.status, step, check });
  } catch (e) {
    o.passed = false;
    o.problem = e instanceof Error ? e.message : String(e);
  }
}

/** Pre-auth if the scrubber asks for it, then the human submit gate, then the payer's 835. */
async function fileAndCollect(claimId: string, step: (s: string) => void, check: (ok: boolean, why: string) => void): Promise<any> {
  const detail = (await call("GET", `/api/v1/claims/${claimId}`)).json;
  const blockers: string[] = (detail.blockers ?? []).map((b: any) => b.code);
  step(`claim built from the verification · expected insurance ${usd(detail.claim?.expectedInsurancePays)} · blockers [${blockers.join(", ") || "none"}]`);
  if (blockers.includes("preauth-missing")) {
    const auth = await call("POST", `/api/v1/claims/${claimId}/preauth`, {
      status: "approved",
      source: "payer-portal",
      referenceNumber: "AUTH-SYNTHETIC-1",
      recordedBy: ACTOR,
    });
    check(auth.status === 200, `recording the pre-authorisation returned HTTP ${auth.status}`);
    step("scrubber held the crown for pre-authorisation; a person recorded AUTH-SYNTHETIC-1");
  }
  const sub = await call("POST", `/api/v1/claims/${claimId}/submit`, { submittedBy: ACTOR });
  check(sub.status === 200, `submit returned HTTP ${sub.status}: ${JSON.stringify(sub.json?.error ?? {}).slice(0, 200)}`);
  step(`a person pressed Submit · 837D control ${sub.json.claim?.submission?.controlNumber ?? "?"}`);
  const rem = await call("POST", "/api/v1/remittances/fetch", {});
  check(rem.status === 200, `fetching remittances returned HTTP ${rem.status}`);
  // The list item, not the detail: it carries what was paid and what is still outstanding.
  const after = ((await call("GET", "/api/v1/claims")).json.items ?? []).find((c: any) => c.id === claimId);
  step(
    `payer's 835 received and posted · claim is now ${after?.status} · fee ${usd(after?.totalFee)}, ` +
      `insurance expected ${usd(after?.expectedInsurancePays)}, paid ${usd(after?.paidAmount)}, outstanding ${usd(after?.outstanding)}`
  );
  return after;
}

await journey(
  "J1",
  "Clean claim: verified, filed, paid in full, posted",
  { firstName: "Avery", lastName: "Synthclean", dateOfBirth: "1986-02-11", memberId: "SYNJ1A41", payer: "Delta Dental" },
  async ({ claimId, step, check }) => {
    check(claimId !== null, "a verified visit produced no claim");
    const claim = await fileAndCollect(claimId!, step, check);
    check(claim?.status === "paid", `expected the claim to be paid, it is ${claim?.status}`);
    check(claim?.outstanding === 0, `a paid claim still shows ${usd(claim?.outstanding)} outstanding`);
  }
);

await journey(
  "J2",
  "Terminated coverage: caught at verification, so no claim is ever built",
  { firstName: "Blake", lastName: "Synthlapsed", dateOfBirth: "1975-07-30", memberId: "SYNJ2B00", payer: "MetLife Dental" },
  async ({ claimId, verificationStatus, step, check }) => {
    check(verificationStatus !== "verified", `terminated coverage was marked ${verificationStatus}`);
    check(claimId === null, "a claim was built for a patient whose coverage is terminated");
    step("no claim built: the front desk is told before the visit, not after the denial");
  }
);

await journey(
  "J3",
  "Denial (CARC 197) → appeal drafted, approved by a person, sent",
  { firstName: "Casey", lastName: "Synthdenied", dateOfBirth: "1991-10-05", memberId: "SYNJ3C77", payer: "Cigna Dental" },
  async ({ claimId, step, check }) => {
    check(claimId !== null, "a verified visit produced no claim");
    await fileAndCollect(claimId!, step, check);
    const denials = (await call("GET", "/api/v1/denials")).json.items ?? [];
    const denial = denials.find((d: any) => d.claimId === claimId);
    check(Boolean(denial), "this claim's denial did not reach the denial queue");
    check(denial.carcCode === "197", `expected CARC 197 (pre-authorisation), the payer gave ${denial.carcCode}`);
    step(
      `denial queued · CARC ${denial.carcCode} on ${denial.procedureCode ?? "the claim"} · ${usd(denial.deniedAmount)} denied · ` +
        `appeal window ${denial.daysToAppeal ?? "?"} days${denial.deadlineEstimated ? " (estimated, not the payer's stated terms)" : ""}`
    );
    const drafted = await call("POST", `/api/v1/denials/${denial.id}/draft`, {});
    check(drafted.status === 200 && drafted.json.activeAppeal?.status === "draft", `drafting the appeal returned HTTP ${drafted.status}`);
    check(drafted.json.canSubmit === false, "a drafted appeal could be sent before a person approved it");
    step("appeal letter drafted with its evidence checklist; it cannot be sent yet");
    const approved = await call("POST", `/api/v1/denials/${denial.id}/approve`, { approvedBy: ACTOR });
    check(approved.status === 200 && approved.json.canSubmit === true, `approving returned HTTP ${approved.status}`);
    const sent = await call("POST", `/api/v1/denials/${denial.id}/submit`, {});
    check(sent.status === 200, `sending the approved appeal returned HTTP ${sent.status}`);
    step(`a person approved it; appeal sent · now ${sent.json.activeAppeal?.status ?? sent.json.denial?.status ?? "sent"}, awaiting the payer`);
  }
);

await journey(
  "J4",
  "Annual maximum nearly used: the estimate lowers the payer's share up front, and the 835's variance is explained",
  { firstName: "Drew", lastName: "Synthshort", dateOfBirth: "1969-04-22", memberId: "SYNJ4D99", payer: "Aetna Dental" },
  async ({ claimId, step, check }) => {
    check(claimId !== null, "a verified visit produced no claim");
    const claim = await fileAndCollect(claimId!, step, check);
    check(
      typeof claim?.expectedInsurancePays === "number" && claim.expectedInsurancePays * 2 < claim.totalFee,
      `the estimate did not anticipate the exhausted maximum: insurance expected ${usd(claim?.expectedInsurancePays)} of ${usd(claim?.totalFee)}`
    );
    step(`estimate before the visit: patient ${usd(claim.expectedPatientPays)}, insurance ${usd(claim.expectedInsurancePays)}`);
    // The mock's "99" lever pays ~40% of what was billed to it, whatever the 271 said remained, so
    // the 835 lands BELOW the estimate. What matters is that the product says so, in its own words.
    check(typeof claim?.variance?.summary === "string", "the claim carries no variance explanation after the 835");
    step(`after the 835: patient owes ${usd(claim.patientResponsibility)} · ${claim.variance.summary}`);
    step(`next: ${claim.recommendedAction}`);
  }
);

await journey(
  "J5",
  "Another plan named on the 835: posting held until a person confirms coverage",
  { firstName: "Emery", lastName: "Synthcob", dateOfBirth: "1982-12-01", memberId: "SYNJ5E23", payer: "MetLife Dental" },
  async ({ claimId, step, check }) => {
    check(claimId !== null, "a verified visit produced no claim");
    await fileAndCollect(claimId!, step, check);
    const cases = (await call("GET", "/api/v1/coordination-cases")).json.items ?? [];
    check(cases.length > 0, "the payer named another plan and no coordination case was opened");
    const held = (await call("GET", "/api/v1/remittances?status=held")).json;
    step(`coordination case opened (${cases.length}); ${held.held ?? 0} advice(s) held, ${usd(held.heldTotal)} waiting on a person`);
  }
);

// ── report ────────────────────────────────────────────────────────────────────────────────────
console.log("\nMermaid revenue cycle, end to end (in memory, mock clearinghouse, synthetic patients)\n");
for (const o of outcomes) {
  console.log(`${o.passed ? "PASS" : "FAIL"}  ${o.id}  ${o.title}`);
  for (const s of o.steps) console.log(`        · ${s}`);
  if (o.problem) console.log(`        ✖ ${o.problem}`);
}
const passed = outcomes.filter((o) => o.passed).length;
console.log(`\n${passed}/${outcomes.length} journeys passed.`);

if (exitAfter) {
  server.close();
  process.exit(passed === outcomes.length ? 0 : 1);
}
console.log(
  `\nThe app is still running with everything above in it:\n  ${base}\n` +
    "  Claims, Recover (denials and appeals), Money (remittances and held advices), Patients.\n" +
    "  In memory: nothing persists after Ctrl+C. No login."
);
