-- 0006_cycle_tables.sql — the revenue-cycle tables: Verification, Claims, Remittance, and the
-- durable domain-event outbox. Completes P2/P3/P4 persistence and closes the project's longest-
-- standing gap (five in-memory repositories + a non-durable outbox).
--
-- ── STORAGE SHAPE: versioned aggregate + extracted columns ──────────────────────────────────
-- Each module's aggregate (VerificationRecord, Claim, Remittance) is stored as ONE versioned JSONB
-- document, alongside plain columns extracted from it for everything we filter, sort, join or
-- report on. This is deliberate, not expedience:
--
--   • The domain objects are deep, already complete, and exhaustively tested against the in-memory
--     repositories. A full row-per-field normalization would demand a large lossy object↔row mapper
--     — precisely the rewrite of working business logic this milestone must avoid.
--   • Every query the application actually issues (by id, by verification_id, by trace number, by
--     status, ordered by recency) is served by an extracted, indexed column. JSONB is never
--     searched in a hot path.
--   • `snapshot_version` on every document is the anti-drift guard established in 0001: an
--     aggregate read back after a shape change is upcast, never silently misread.
--
-- The aggregate document is AUTHORITATIVE. Extracted columns are derived on write and must never be
-- the source of truth for money — a discrepancy is a bug in the repository, not a business fact.
--
-- Deliberately deferred: a normalized `claim_lines` projection (blueprint doc 03). Nothing consumes
-- line-level rows yet — Analytics and Payer Profile do not exist — and the lines live in the claim
-- document, so the projection can be backfilled by a single INSERT…SELECT jsonb_array_elements
-- when the first consumer lands. Building it now would be untested surface with no reader.
--
-- ── MONEY ───────────────────────────────────────────────────────────────────────────────────
-- Every money column is BIGINT holding INTEGER CENTS (design decision §12.1). BIGINT rather than
-- INTEGER because practice-level aggregates exceed int4's ~$21.4M ceiling; values stay far inside
-- JavaScript's 2^53 safe-integer range, and pool.ts parses int8 as a number accordingly.
--
-- ── TENANCY ─────────────────────────────────────────────────────────────────────────────────
-- Every table here is tenant-scoped under RLS via enable_tenant_rls (0002). The one narrow, audited
-- exception is the outbox worker, which must see every practice's events — see claim_domain_events
-- at the bottom of this file.

-- ═══════════════════════════════════════════════════════════════════════════════════════════
-- Verification
-- ═══════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE verifications (
  -- Ids are generated by the module (randomUUID), not by the database: the aggregate exists and is
  -- fully formed before it is ever persisted, and its id is already embedded in the document.
  id                  UUID PRIMARY KEY,
  practice_id         UUID NOT NULL REFERENCES practices(id),
  -- Nullable while the demo runs without a patient master record; becomes NOT NULL when the
  -- verification flow writes `patients` rows (it reads them today, it does not create them).
  patient_id          UUID REFERENCES patients(id),

  status              TEXT NOT NULL CHECK (status IN ('verified','needs_review','reviewed','failed')),
  payer_id            TEXT,
  member_id           TEXT,
  patient_first_name  TEXT NOT NULL,
  patient_last_name   TEXT NOT NULL,
  -- 0.000–1.000; a read-model input, never money.
  confidence          NUMERIC(4,3),
  total_fee_cents     BIGINT,
  patient_pays_cents  BIGINT,

  record              JSONB NOT NULL,
  created_at          TIMESTAMPTZ NOT NULL,
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT verifications_record_versioned CHECK (jsonb_has_version(record))
);
-- The queue query: this practice's verifications, newest first, optionally by status.
CREATE INDEX idx_verifications_queue ON verifications (practice_id, created_at DESC);
CREATE INDEX idx_verifications_status ON verifications (practice_id, status, created_at DESC);
CREATE TRIGGER trg_verifications_updated BEFORE UPDATE ON verifications
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
SELECT enable_tenant_rls('verifications');

-- ═══════════════════════════════════════════════════════════════════════════════════════════
-- Claims
-- ═══════════════════════════════════════════════════════════════════════════════════════════

CREATE TABLE claims (
  id                        UUID PRIMARY KEY,
  practice_id               UUID NOT NULL REFERENCES practices(id),

  -- THE KEYSTONE (blueprint doc 00). A claim inherits one verification's frozen estimate. The
  -- UNIQUE constraint is what makes event-driven creation idempotent under at-least-once delivery:
  -- two claims for one visit is a duplicate-billing incident, so the database refuses it outright
  -- rather than trusting the service guard alone.
  verification_id           UUID NOT NULL,

  status                    TEXT NOT NULL CHECK (status IN
                              ('draft','ready','submitted','rejected','partially_paid','denied','paid','void')),
  payer_id                  TEXT,
  payer_name                TEXT,
  member_id                 TEXT NOT NULL,
  patient_first_name        TEXT NOT NULL,
  patient_last_name         TEXT NOT NULL,

  service_date              DATE NOT NULL,
  filing_deadline           DATE NOT NULL,

  total_fee_cents           BIGINT NOT NULL,
  expected_insurance_cents  BIGINT NOT NULL,
  expected_patient_cents    BIGINT NOT NULL,
  paid_cents                BIGINT NOT NULL DEFAULT 0,

  -- The clinic's control number (837 CLM01), echoed back by the payer in the 835's CLP01. Null
  -- until submission. This is the key a payment is matched on.
  patient_control_number    TEXT,

  record                    JSONB NOT NULL,
  created_at                TIMESTAMPTZ NOT NULL,
  updated_at                TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT claims_record_versioned CHECK (jsonb_has_version(record)),
  CONSTRAINT claims_one_per_verification UNIQUE (practice_id, verification_id)
);
CREATE INDEX idx_claims_queue ON claims (practice_id, created_at DESC);
CREATE INDEX idx_claims_status ON claims (practice_id, status, created_at DESC);
-- Timely-filing sweeps scan open claims by deadline; a partial index keeps it small as history grows.
CREATE INDEX idx_claims_open_deadline ON claims (practice_id, filing_deadline)
  WHERE status IN ('draft','ready','rejected','partially_paid','denied');
CREATE TRIGGER trg_claims_updated BEFORE UPDATE ON claims
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
SELECT enable_tenant_rls('claims');

-- ═══════════════════════════════════════════════════════════════════════════════════════════
-- Remittance
-- ═══════════════════════════════════════════════════════════════════════════════════════════

-- What the clinic was promised, projected from `claim.submitted`. The Remittance module may not
-- read the Claims tables (docs/MODULE-BOUNDARIES.md), so it keeps its own event-sourced ledger.
-- Keyed on the CLINIC's control number, because that is the only identifier the payer echoes back.
CREATE TABLE claim_expectations (
  practice_id               UUID NOT NULL REFERENCES practices(id),
  patient_control_number    TEXT NOT NULL,
  claim_id                  UUID NOT NULL,
  verification_id           UUID NOT NULL,
  payer_id                  TEXT,
  payer_name                TEXT,
  submitted_at              TIMESTAMPTZ NOT NULL,
  service_date              DATE NOT NULL,
  total_fee_cents           BIGINT NOT NULL,
  expected_insurance_cents  BIGINT NOT NULL,
  created_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (practice_id, patient_control_number)
);
CREATE TRIGGER trg_claim_expectations_updated BEFORE UPDATE ON claim_expectations
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
SELECT enable_tenant_rls('claim_expectations');

CREATE TABLE remittances (
  id                    UUID PRIMARY KEY,
  practice_id           UUID NOT NULL REFERENCES practices(id),

  -- THE IDEMPOTENCY KEY. One check or EFT trace posts exactly once. Enforced by the database, not
  -- only by the service: a clearinghouse re-serving an ERA, the outbox re-delivering, and staff
  -- re-uploading a file are all normal traffic, and a double-posted remittance corrupts the ledger
  -- a practice bills patients and reports revenue from.
  trace_number          TEXT NOT NULL,

  status                TEXT NOT NULL CHECK (status IN ('held','posted')),
  payer_name            TEXT NOT NULL,
  payee_name            TEXT NOT NULL,
  payment_total_cents   BIGINT NOT NULL,
  payment_method        TEXT,
  payment_date          DATE,
  balanced              BOOLEAN NOT NULL,
  hold_reason           TEXT,

  -- Raw 835 kept for provenance. PHI + financial detail: moved behind column encryption with the
  -- rest of the raw-payload columns (risk §4). Never logged.
  raw_835               TEXT,

  record                JSONB NOT NULL,
  received_at           TIMESTAMPTZ NOT NULL,
  updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT remittances_record_versioned CHECK (jsonb_has_version(record)),
  CONSTRAINT remittances_one_per_trace UNIQUE (practice_id, trace_number)
);
CREATE INDEX idx_remittances_queue ON remittances (practice_id, received_at DESC);
CREATE INDEX idx_remittances_status ON remittances (practice_id, status, received_at DESC);
CREATE TRIGGER trg_remittances_updated BEFORE UPDATE ON remittances
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
SELECT enable_tenant_rls('remittances');

-- One posting per claim payment. A queryable projection of the postings inside the remittance
-- aggregate: this is the table the recovery queue and revenue reporting read, and it is what makes
-- "where is our missing revenue?" an indexed query rather than a scan of JSONB documents.
CREATE TABLE postings (
  id                        UUID PRIMARY KEY,
  practice_id               UUID NOT NULL REFERENCES practices(id),
  remittance_id             UUID NOT NULL REFERENCES remittances(id) ON DELETE CASCADE,

  -- Null when the payer paid a claim we have no record of filing. The money is real and is still
  -- posted; someone has to identify it.
  claim_id                  UUID,
  patient_control_number    TEXT NOT NULL,
  payer_control_number      TEXT,
  patient_name              TEXT,

  charged_cents             BIGINT NOT NULL,
  paid_cents                BIGINT NOT NULL,
  patient_resp_cents        BIGINT NOT NULL,

  -- The four-way attribution of every withheld dollar. Null when the payment could not be matched
  -- to an expectation: a variance against an unknown baseline is a fabricated number.
  expected_insurance_cents  BIGINT,
  contractual_cents         BIGINT,
  recoverable_cents         BIGINT,
  unexplained_cents         BIGINT,
  variance_cents            BIGINT,
  outcome                   TEXT,
  actionable                BOOLEAN NOT NULL DEFAULT false,

  posted_at                 TIMESTAMPTZ NOT NULL,
  created_at                TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_postings_remittance ON postings (remittance_id);
CREATE INDEX idx_postings_claim ON postings (practice_id, claim_id);
-- The recovery queue: only postings still holding money someone owes us.
CREATE INDEX idx_postings_recovery ON postings (practice_id, posted_at DESC) WHERE actionable;
SELECT enable_tenant_rls('postings');

-- ═══════════════════════════════════════════════════════════════════════════════════════════
-- Domain-event outbox
-- ═══════════════════════════════════════════════════════════════════════════════════════════

-- An event is appended in the SAME transaction as the business write that caused it, so an event
-- can never be lost, nor emitted for a write that rolled back (platform/events/README.md).
CREATE TABLE domain_events (
  id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  practice_id     UUID NOT NULL REFERENCES practices(id),
  event_type      TEXT NOT NULL,
  aggregate_id    TEXT NOT NULL,
  payload         JSONB NOT NULL,
  occurred_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

  attempts        INTEGER NOT NULL DEFAULT 0,
  -- Exponential backoff: a failing subscriber must not be hammered, and must not block the queue.
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  published_at    TIMESTAMPTZ,
  last_error      TEXT,
  dead_lettered   BOOLEAN NOT NULL DEFAULT false,

  CONSTRAINT domain_events_payload_versioned CHECK (jsonb_has_version(payload))
);
-- The worker's hot query. Partial index: published and dead-lettered rows are the overwhelming
-- majority over time and are excluded entirely, so the index stays proportional to the BACKLOG
-- rather than to history — the difference between a queue that scales to hundreds of practices and
-- one that degrades as it succeeds.
CREATE INDEX idx_domain_events_pending ON domain_events (next_attempt_at, occurred_at)
  WHERE published_at IS NULL AND dead_lettered = false;
CREATE INDEX idx_domain_events_practice ON domain_events (practice_id, occurred_at DESC);
CREATE INDEX idx_domain_events_dead ON domain_events (practice_id, occurred_at DESC) WHERE dead_lettered;
SELECT enable_tenant_rls('domain_events');

-- Per-subscriber checkpointing. If two subscribers take one event and only one throws, the retry
-- re-delivers to the FAILED subscriber only — otherwise a flaky consumer forces duplicate work on a
-- healthy one on every retry.
CREATE TABLE domain_event_deliveries (
  event_id      UUID NOT NULL REFERENCES domain_events(id) ON DELETE CASCADE,
  subscriber    TEXT NOT NULL,
  practice_id   UUID NOT NULL REFERENCES practices(id),
  delivered_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (event_id, subscriber)
);
SELECT enable_tenant_rls('domain_event_deliveries');

-- ── The worker's narrow, audited hole through RLS ────────────────────────────────────────────
--
-- The dispatcher must see every practice's backlog; a per-practice poll would mean one query per
-- tenant per tick, which does not scale to hundreds of clinics. These SECURITY DEFINER functions
-- are the same pattern as find_user_for_auth (0003): a tightly-scoped, reviewable bypass rather
-- than an application role that can read across tenants.
--
-- Handlers are still invoked under set_current_practice(event.practice_id), so all module code runs
-- fully RLS-scoped. Only the queue mechanics see across tenants, and they touch no PHI beyond the
-- payload they are transporting.

-- Claim a batch: FOR UPDATE SKIP LOCKED lets N workers run concurrently without double-processing
-- and without blocking each other on a contended row.
CREATE OR REPLACE FUNCTION claim_domain_events(p_limit integer)
RETURNS SETOF domain_events
LANGUAGE sql SECURITY DEFINER
SET search_path = public
AS $$
  UPDATE domain_events e
     SET attempts = e.attempts + 1
   WHERE e.id IN (
     SELECT c.id
       FROM domain_events c
      WHERE c.published_at IS NULL
        AND c.dead_lettered = false
        AND c.next_attempt_at <= now()
      ORDER BY c.occurred_at
      FOR UPDATE SKIP LOCKED
      LIMIT p_limit
   )
  RETURNING e.*;
$$;

-- Record a successful delivery to one subscriber (idempotent).
CREATE OR REPLACE FUNCTION mark_event_delivered(p_event_id uuid, p_subscriber text, p_practice_id uuid)
RETURNS void
LANGUAGE sql SECURITY DEFINER
SET search_path = public
AS $$
  INSERT INTO domain_event_deliveries (event_id, subscriber, practice_id)
  VALUES (p_event_id, p_subscriber, p_practice_id)
  ON CONFLICT (event_id, subscriber) DO NOTHING;
$$;

-- Which subscribers have already taken this event.
CREATE OR REPLACE FUNCTION event_delivered_subscribers(p_event_id uuid)
RETURNS SETOF text
LANGUAGE sql SECURITY DEFINER
SET search_path = public
AS $$
  SELECT subscriber FROM domain_event_deliveries WHERE event_id = p_event_id;
$$;

-- Settle an event: fully published, or failed and rescheduled, or dead-lettered.
CREATE OR REPLACE FUNCTION settle_domain_event(
  p_event_id uuid,
  p_published boolean,
  p_error text,
  p_max_attempts integer,
  p_backoff_seconds integer
) RETURNS void
LANGUAGE sql SECURITY DEFINER
SET search_path = public
AS $$
  UPDATE domain_events
     SET published_at    = CASE WHEN p_published THEN now() ELSE NULL END,
         last_error      = CASE WHEN p_published THEN NULL ELSE p_error END,
         dead_lettered   = (NOT p_published AND attempts >= p_max_attempts),
         next_attempt_at = CASE WHEN p_published THEN next_attempt_at
                                ELSE now() + make_interval(secs => p_backoff_seconds) END
   WHERE id = p_event_id;
$$;

-- Operational visibility: the mandated outbox-lag signal (blueprint doc 13). The feedback loop is
-- the product thesis and must never stall silently.
CREATE OR REPLACE FUNCTION domain_event_backlog()
RETURNS TABLE (pending bigint, dead bigint, oldest_pending timestamptz)
LANGUAGE sql SECURITY DEFINER
SET search_path = public
AS $$
  SELECT count(*) FILTER (WHERE published_at IS NULL AND dead_lettered = false),
         count(*) FILTER (WHERE dead_lettered),
         min(occurred_at) FILTER (WHERE published_at IS NULL AND dead_lettered = false)
    FROM domain_events;
$$;
